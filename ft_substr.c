#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	size_t	s_len;
	char	*ptr;
	char	*ptr_start;

	s_len = ft_strlen(s);
	if (start >= s_len)
		return (ft_strdup(""));
	if (len > s_len - start)
		len = s_len - start;
	ptr = malloc(len + 1);
	if (!ptr)
		return (NULL);
	ptr_start = ptr;
	s += start;
	while (len-- && *s)
		*ptr++ = *s++;
	*ptr = '\0';
	return (ptr_start);
}
